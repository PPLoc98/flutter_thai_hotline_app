// ตัวแปรที่ล้อกับข้อมูลต่างๆ
class Hotline {
  // ตัวแปรที่ล้อกับข้อมูลต่างๆ ที่เราจะทำงานด้วย
  final String name; //ชื่อสายด่วน
  final String number; //เบอร์โทร
  final String icon; //รูปภาพ

// constructor ที่เราจะใช้เชื่อมข้อมูลจากname class Hotline
  Hotline({
    required this.name,
    required this.number,
    required this.icon,
  });
}
